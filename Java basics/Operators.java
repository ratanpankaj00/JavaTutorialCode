public class Operators {
    public static void main(String[] args) {
        
        int a = 24;
        int b = a % 7;
        System.out.println(b); // Ans. 3
        System.out.println(4<=4); // True

        // Arithematic Operators: + - * / ++ -- %
        // Assingment Operators: += =
        // Comparison Operators: == >= <=
        // Logical Operator: && || !
        // Bitwise Operator: & | (Operates Bitwise)

        System.out.println(45>4 && 6<5); // atleast one the statement is incorrect then False, else TRUE 
        System.out.println(8==9 || 8<=7); // atleast one the statement is correct then True, else False
    }
}
